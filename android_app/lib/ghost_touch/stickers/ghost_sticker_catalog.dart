enum GhostStickerCategory {
  love,
  cosmic,
  cyberpunk,
  cute,
  presence,
  celebration,
}

extension GhostStickerCategoryExt on GhostStickerCategory {
  String label(bool isFa) {
    switch (this) {
      case GhostStickerCategory.love:
        return isFa ? 'عشق و احساس' : 'Love';
      case GhostStickerCategory.cosmic:
        return isFa ? 'کیهان و فضا' : 'Cosmic';
      case GhostStickerCategory.cyberpunk:
        return isFa ? 'سایبرپانک' : 'Cyberpunk';
      case GhostStickerCategory.cute:
        return isFa ? 'کیوت و بامزه' : 'Cute';
      case GhostStickerCategory.presence:
        return isFa ? 'حضور و پیام مخفی' : 'Presence';
      case GhostStickerCategory.celebration:
        return isFa ? 'جشن و غافلگیری' : 'Celebrate';
    }
  }

  Color get accentColor {
    switch (this) {
      case GhostStickerCategory.love:
        return GhostPalette.neonPink;
      case GhostStickerCategory.cosmic:
        return GhostPalette.electricBlue;
      case GhostStickerCategory.cyberpunk:
        return GhostPalette.electricCyan;
      case GhostStickerCategory.cute:
        return const Color(0xFFFF90B3);
      case GhostStickerCategory.presence:
        return GhostPalette.neonGreen;
      case GhostStickerCategory.celebration:
        return GhostPalette.amberGold;
    }
  }
}

