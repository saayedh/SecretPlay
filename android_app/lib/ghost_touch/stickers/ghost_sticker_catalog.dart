  static List<GhostStickerDef> byCategory(GhostStickerCategory category) {
    return all.where((s) => s.category == category).toList(growable: false);
  }

  static GhostStickerDef findById(String? id) {
    if (id != null && id.isNotEmpty) {
      final direct = _byId[id];
      if (direct != null) return direct;
      final mappedId = _legacyMap[id];
      if (mappedId != null && _byId[mappedId] != null) {
        return _byId[mappedId]!;
      }
    }
    return all.first;
  }
